import java.util.Scanner;

public class DisplayPlaces {
    public static void main(String[] args) {
        long n=1101001000;
        System.out.println("Unit Digit is: " + n%10);
        System.out.println("Tens Digit is: " + n%100);
        System.out.print("Thousands Digit is: " + n%1000);

    }
}
