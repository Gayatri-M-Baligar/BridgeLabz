package com.bridgeLabz.EmployeeProblem;

public class EmployeeWageUC4 {
    public static void main(String[] args) {

        // Define wage per hour
        int wagePerHour = 20;

        // Define part-time working hours
        int partTimeHours = 8;

        // Calculate part-time employee wage
        int empWage = wagePerHour * partTimeHours;

        // Display part-time employee wage
        System.out.println("Part Time Employee Wage: " + empWage);
    }
}
